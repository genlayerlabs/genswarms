// The multilingual build (playbook §2-6, §10-11). English in src/ is the single source; website/i18n/<lang>.json are
// the translations. build() renders every version in memory and refuses (writes nothing) on a stale catalogue, a
// missing id, changed markup or placeholders, a dropped protected name, a snippet over its limit, a page over the
// size budget, or English left on a translated page.
import { createHash } from 'node:crypto';
import { readFileSync, existsSync, readdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { LANGS, ORIGIN, PROTECT, withLang, t, validate, staleIds, textRuns, decode } from './i18n.mjs';
import { renderPage } from './page.mjs';
import { render404, strings404 } from './notfound.mjs';

export const WEB = new URL('../', import.meta.url);             // website/
export const SRC = new URL('./', import.meta.url);              // website/src/
const dirURL = p => pathToFileURL(resolve(p) + '/');
// I18N_DIR (translations, catalogue, locks) and OUT_DIR (the site root) override website/i18n and website/
export const defaults = () => ({
  i18nDir: process.env.I18N_DIR ? dirURL(process.env.I18N_DIR) : new URL('i18n/', WEB),
  outDir: process.env.OUT_DIR ? dirURL(process.env.OUT_DIR) : WEB,
});
export const MAX_BYTES = 153600;
const LASTMOD = '2026-09-25';
const sha = b => createHash('sha256').update(b).digest('hex');
const read = u => (existsSync(u) ? readFileSync(u) : null);

// The suggestion bar's strings (src/langbar.js); each version carries them for every language, since the bar is
// shown in the language it offers.
export const barStrings = () => ({
  msg: t('This page is also available in English.', 'suggestion bar: one line shown to visitors whose browser prefers your language, on a page in another language. Name your language as a reader would (“…in Spanish” → “…en español”)', { kind: 'js' }),
  go: t('Read it in English', 'suggestion bar: the link to this version (short; name your language)', { kind: 'js' }),
  close: t('Dismiss', 'suggestion bar: accessible name of the × button that closes it', { kind: 'js' }),
});

